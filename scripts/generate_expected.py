
"""Generate expected OCR results for the test images.

Writes tests/test_files/expected/<tesseract-version>/<stem>.json
containing the words and counts the current pipeline detects,
marked as generated and pending human review.

Expectations are versioned because Tesseract releases detect
different words from the same image. CI uses --output-dir to
upload a fixture set for the version installed on its runner.

This is a generation tool, not a test. Run it after
intentional OCR changes to refresh the expectations:

    uv run python scripts/generate_expected.py
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(
    __file__
).resolve().parents[1]

sys.path.insert(
    0,
    str(ROOT / "src")
)

from braille_converter.ocr_engine import (  # noqa: E402
    configure_tesseract,
    recognize_characters
)


def tesseract_version():

    configure_tesseract()

    import pytesseract

    return str(
        pytesseract.get_tesseract_version()
    )


# Exact counts are only comparable against the same
# Tesseract version. The floor below guards against a
# catastrophic OCR regression on any version while
# tolerating normal version-to-version variance (a
# newer Tesseract detected about 54% of the recorded
# words on the densest test image).
MIN_WORD_RATIO = 0.4


def expected_for(image_path, version):

    records = recognize_characters(
        image_path
    )

    groups = {}

    for record in records:

        groups.setdefault(
            record.group_id,
            []
        ).append(record)

    words = []

    for group in groups.values():

        group.sort(
            key=lambda r: r.x1
        )

        words.append({
            "text": "".join(
                r.text for r in group
            ),
            "count": len(group),
            "source": group[
                0
            ].source_word
        })

    return {
        "image": image_path.name,
        "status": (
            "generated by "
            "scripts/generate_expected.py; "
            "human review pending"
        ),
        "tesseract_version": version,
        "word_count": len(words),
        "min_word_count": max(
            1,
            int(len(words) * MIN_WORD_RATIO)
        ),
        "record_count": len(records),
        "words": words
    }


def main(argv=None):

    parser = argparse.ArgumentParser(
        description=(
            "Generate OCR expectations for the "
            "installed Tesseract version."
        )
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Root for the versioned fixture "
            "directory (default: "
            "tests/test_files/expected)."
        )
    )

    args = parser.parse_args(argv)

    test_dir = (
        ROOT / "tests" / "test_files"
    )

    version = tesseract_version()

    output_root = (
        args.output_dir
        or test_dir / "expected"
    )

    expected_dir = output_root / version

    expected_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    images = sorted(
        test_dir.glob("*.jpg")
    )

    if not images:
        print(
            f"FAIL: no test images in "
            f"{test_dir}"
        )

        return 1

    print(f"Tesseract {version}")

    for image in images:

        payload = expected_for(
            image,
            version
        )

        target = (
            expected_dir
            / f"{image.stem}.json"
        )

        target.write_text(
            json.dumps(
                payload,
                ensure_ascii=False,
                indent=2
            ),
            encoding="utf-8"
        )

        print(
            f"{image.stem}: "
            f"{payload['word_count']} words, "
            f"{payload['record_count']} records"
        )

    print(f"Fixtures written to {expected_dir}")

    return 0


if __name__ == "__main__":

    sys.exit(main())
