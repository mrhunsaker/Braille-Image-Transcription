
"""Generate expected OCR results for the test images.

Writes tests/test_files/expected/<stem>.json containing
the words and mean confidence the current pipeline
detects, marked as generated and pending human review.

This is a generation tool, not a test. Run it after
intentional OCR changes to refresh the expectations:

    uv run python scripts/generate_expected.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(
    __file__
).resolve().parents[1]

sys.path.insert(
    0,
    str(ROOT / "src")
)

from braille_converter.ocr_engine import (
    recognize_characters
)


def expected_for(image_path):

    records = recognize_characters(
        image_path
    )

    groups = {}

    for record in records:

        groups.setdefault(
            record.group_id,
            []
        ).append(record)

    words = []

    for group in groups.values():

        group.sort(
            key=lambda r: r.x1
        )

        words.append({
            "text": "".join(
                r.text for r in group
            ),
            "count": len(group),
            "source": group[
                0
            ].source_word
        })

    return {
        "image": image_path.name,
        "status": (
            "generated by "
            "scripts/generate_expected.py; "
            "human review pending"
        ),
        "word_count": len(words),
        "record_count": len(records),
        "words": words
    }


def main():

    test_dir = (
        ROOT / "tests" / "test_files"
    )

    expected_dir = (
        test_dir / "expected"
    )

    expected_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    images = sorted(
        test_dir.glob("*.jpg")
    )

    if not images:
        print(
            f"FAIL: no test images in "
            f"{test_dir}"
        )

        return 1

    for image in images:

        payload = expected_for(image)

        target = (
            expected_dir
            / f"{image.stem}.json"
        )

        target.write_text(
            json.dumps(
                payload,
                ensure_ascii=False,
                indent=2
            ),
            encoding="utf-8"
        )

        print(
            f"{image.stem}: "
            f"{payload['word_count']} words, "
            f"{payload['record_count']} records"
        )

    return 0


if __name__ == "__main__":

    sys.exit(main())
